/**
 * Generates the QR matrix for every ball, once, into src/lib/ballCodes.ts.
 *
 * The payload is deliberately tiny ("DMB7"): fewer modules means bigger
 * modules on a 14mm sticker, which is the whole difference between a label
 * that scans off a curved ball and one that does not. All 90 fit a 21x21 grid
 * at error-correction level H (30% of the code can be scuffed and it still
 * reads), so every sticker is the same size.
 *
 * Run with:  node scripts/gen-ball-codes.mjs      (needs: npm i qrcode)
 */
import QR from 'qrcode';
import { writeFileSync } from 'node:fs';

const SIZE = 21;
const rows = [];

for (let n = 1; n <= 90; n++) {
  const qr = QR.create(`DMB${n}`, { errorCorrectionLevel: 'H' });
  if (qr.modules.size !== SIZE) throw new Error(`ball ${n}: unexpected grid ${qr.modules.size}`);

  // one hex word per row, most significant bit = leftmost module
  const hex = [];
  for (let y = 0; y < SIZE; y++) {
    let bits = 0;
    for (let x = 0; x < SIZE; x++) {
      bits = (bits << 1) | (qr.modules.get(x, y) ? 1 : 0);
    }
    hex.push(bits.toString(16).padStart(6, '0'));
  }
  rows.push(`  ${n}: '${hex.join('')}',`);
}

writeFileSync(
  'src/lib/ballCodes.ts',
  `// GENERATED by scripts/gen-ball-codes.mjs — do not edit by hand.
//
// One QR code per ball, 21x21 modules, error-correction level H.
// Each entry is 21 rows of 6 hex characters; within a row the most significant
// of the low 21 bits is the leftmost module.

/** modules per side */
export const QR_SIZE = ${SIZE};

/** what a scanner reads off ball n */
export const ballPayload = (n: number) => \`DMB\${n}\`;

const PACKED: Record<number, string> = {
${rows.join('\n')}
};

/** The matrix for one ball as rows of booleans, or null for an unknown ball. */
export function ballMatrix(n: number): boolean[][] | null {
  const packed = PACKED[n];
  if (!packed) return null;

  const out: boolean[][] = [];
  for (let y = 0; y < QR_SIZE; y++) {
    const bits = parseInt(packed.slice(y * 6, y * 6 + 6), 16);
    const row: boolean[] = [];
    for (let x = 0; x < QR_SIZE; x++) {
      row.push(((bits >> (QR_SIZE - 1 - x)) & 1) === 1);
    }
    out.push(row);
  }
  return out;
}
`
);
console.log('wrote src/lib/ballCodes.ts for 90 balls');
